"""Name every recorded GraphQL request of a raw run again, by the documents table beside this
file (the v0.11.0 one, regenerated by `dump_documents.sh`), and count the aliased mutations
each mutation request carried (the fields its answer's `data` holds). Rewrites the run's
`proxy.jsonl` in place, keeping the original as `proxy.v0.jsonl`.

Usage: python3 relabel.py RAW_RUN_DIR...
"""

import json
import sys
from pathlib import Path

import proxy


def relabel(run: Path) -> None:
    log = run / "proxy.jsonl"
    if not log.exists():
        return
    original = run / "proxy.v0.jsonl"
    if not original.exists():
        original.write_text(log.read_text())
    bodies = run / "proxy.bodies"
    out = []
    for line in original.read_text().splitlines():
        record = json.loads(line)
        if record["path"].startswith("/graphql") and record["kind"] in ("query", "mutation"):
            request = bodies / f"{record['seq']:06d}.req"
            if request.exists():
                record["kind"], record["op"] = proxy.operation_of(
                    json.loads(request.read_text()).get("query", "")
                )
            if record["kind"] == "mutation" and record["host"] != "refused":
                answer = bodies / f"{record['seq']:06d}.resp"
                data = (json.loads(answer.read_text() or "{}").get("data") or {}) if answer.exists() else {}
                record["mutations"] = sum(1 for v in data.values() if v is not None)
        out.append(record)
    log.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in out))


if __name__ == "__main__":
    for arg in sys.argv[1:]:
        relabel(Path(arg))
